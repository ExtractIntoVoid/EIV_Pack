namespace EIV_Pack;

/// <summary>
/// Packable generator options.
/// </summary>
public enum GenerateType
{
    /// <summary>
    /// No generate option.
    /// </summary>
    None,

    /// <summary>
    /// Generate a version tolerant version.
    /// </summary>
    VersionTolerant,

    /// <summary>
    /// Nothing will be generated.
    /// </summary>
    NoGenerate,
}
